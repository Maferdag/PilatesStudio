-- Esquema PostgreSQL para Pilates Studio (Supabase).
-- Ejecutar en el SQL Editor de Supabase sobre una base vacía.
-- Las tablas se crean en public y los IDs usan identity autoincremental.
--
-- El backend Flask debe conectarse con el rol pilates_app, no con el
-- propietario de las tablas ni con un rol que tenga BYPASSRLS. El rol se
-- crea sin contraseña; configura su contraseña de forma segura fuera de este
-- archivo y usa POSTGRES_USER=pilates_app en las variables del backend.

CREATE TABLE IF NOT EXISTS public.usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo varchar(100) NOT NULL UNIQUE,
    contrasena_hash varchar(200) NOT NULL,
    rol varchar(20) NOT NULL DEFAULT 'alumno',
    estado_aprobacion varchar(20) NOT NULL DEFAULT 'aprobado'
);

CREATE TABLE IF NOT EXISTS public.clases (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_clase varchar(100) NOT NULL,
    duracion_minutos integer NOT NULL
);

CREATE TABLE IF NOT EXISTS public.planes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_plan varchar(100) NOT NULL,
    precio double precision NOT NULL,
    cantidad_clases integer
);

CREATE TABLE IF NOT EXISTS public.alumnos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL UNIQUE
        REFERENCES public.usuarios (id),
    nombre_completo varchar(150) NOT NULL,
    telefono varchar(20)
);

CREATE TABLE IF NOT EXISTS public.instructores (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer UNIQUE
        REFERENCES public.usuarios (id),
    nombre_completo varchar(150) NOT NULL,
    especialidad varchar(100)
);

CREATE TABLE IF NOT EXISTS public.horarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_clase integer NOT NULL
        REFERENCES public.clases (id),
    id_instructor integer NOT NULL
        REFERENCES public.instructores (id),
    fecha date NOT NULL,
    hora time without time zone NOT NULL,
    cupo_maximo integer NOT NULL
);

CREATE TABLE IF NOT EXISTS public.reservas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_alumno integer NOT NULL
        REFERENCES public.alumnos (id),
    id_horario integer NOT NULL
        REFERENCES public.horarios (id),
    estado varchar(20) DEFAULT 'confirmada',
    fecha_reserva timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.asistencias (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva integer NOT NULL UNIQUE
        REFERENCES public.reservas (id),
    estado varchar(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.pagos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_alumno integer NOT NULL
        REFERENCES public.alumnos (id),
    id_plan integer NOT NULL
        REFERENCES public.planes (id),
    fecha_pago date NOT NULL,
    monto double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS public.lista_espera (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_alumno integer NOT NULL
        REFERENCES public.alumnos (id),
    id_horario integer NOT NULL
        REFERENCES public.horarios (id)
);

CREATE TABLE IF NOT EXISTS public.notificaciones (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL
        REFERENCES public.usuarios (id),
    mensaje varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.recuperacion_password (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL
        REFERENCES public.usuarios (id),
    token varchar(100) NOT NULL UNIQUE
);

-- Índices para las relaciones y consultas habituales de la aplicación.
CREATE INDEX IF NOT EXISTS ix_horarios_id_clase
    ON public.horarios (id_clase);
CREATE INDEX IF NOT EXISTS ix_horarios_id_instructor
    ON public.horarios (id_instructor);
CREATE INDEX IF NOT EXISTS ix_horarios_fecha_hora
    ON public.horarios (fecha, hora);
CREATE INDEX IF NOT EXISTS ix_reservas_id_alumno
    ON public.reservas (id_alumno);
CREATE INDEX IF NOT EXISTS ix_reservas_id_horario
    ON public.reservas (id_horario);
CREATE INDEX IF NOT EXISTS ix_reservas_fecha_reserva
    ON public.reservas (fecha_reserva);
CREATE INDEX IF NOT EXISTS ix_asistencias_estado
    ON public.asistencias (estado);
CREATE INDEX IF NOT EXISTS ix_pagos_id_alumno
    ON public.pagos (id_alumno);
CREATE INDEX IF NOT EXISTS ix_pagos_id_plan
    ON public.pagos (id_plan);
CREATE INDEX IF NOT EXISTS ix_lista_espera_id_horario
    ON public.lista_espera (id_horario);
CREATE INDEX IF NOT EXISTS ix_notificaciones_id_usuario
    ON public.notificaciones (id_usuario);
CREATE INDEX IF NOT EXISTS ix_recuperacion_password_id_usuario
    ON public.recuperacion_password (id_usuario);

-- Permisos de ejecución del backend. El rol no recibe permisos de DDL.
GRANT USAGE ON SCHEMA public TO pilates_app;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON public.usuarios, public.clases, public.planes, public.alumnos,
       public.instructores, public.horarios, public.reservas,
       public.asistencias, public.pagos, public.lista_espera,
       public.notificaciones, public.recuperacion_password
    TO pilates_app;
GRANT USAGE, SELECT, UPDATE
    ON SEQUENCE public.usuarios_id_seq, public.clases_id_seq,
       public.planes_id_seq, public.alumnos_id_seq,
       public.instructores_id_seq, public.horarios_id_seq,
       public.reservas_id_seq, public.asistencias_id_seq,
       public.pagos_id_seq, public.lista_espera_id_seq,
       public.notificaciones_id_seq, public.recuperacion_password_id_seq
    TO pilates_app;

-- RLS permite todas las operaciones al rol privado del backend Flask.
-- No se conceden permisos ni políticas a anon/authenticated: la API pública
-- de Supabase no puede acceder a estas tablas con estas políticas.
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS pilates_app_access ON public.usuarios;
CREATE POLICY pilates_app_access ON public.usuarios
    FOR ALL TO pilates_app USING (true) WITH CHECK (true);

